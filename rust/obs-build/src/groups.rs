//! Preserve explicit source inventories while compiling each member separately.
use std::{
    collections::HashSet,
    fs,
    path::{Path, PathBuf},
};

pub(crate) fn headers(
    root: &Path,
    sources: &[PathBuf],
) -> Result<Vec<crate::PrecompiledHeader>, String> {
    let mut headers = std::collections::BTreeMap::<PathBuf, Vec<PathBuf>>::new();
    for source in sources {
        let content =
            fs::read_to_string(source).map_err(|e| format!("read {}: {e}", source.display()))?;
        let first = content.lines().map(str::trim).find(|line| {
            !line.is_empty()
                && !line.starts_with("/*")
                && !line.starts_with('*')
                && !line.starts_with("//")
        });
        let Some(include) = first
            .and_then(|line| line.strip_prefix("#include \""))
            .and_then(|line| line.strip_suffix('"'))
        else {
            continue;
        };
        if !(include.ends_with(".pch.h") || include.ends_with(".pch.hpp")) {
            continue;
        }
        let header =
            dunce::canonicalize(root.join(include)).map_err(|e| format!("PCH {include}: {e}"))?;
        headers.entry(header).or_default().push(source.clone());
    }
    Ok(headers
        .into_iter()
        .map(|(header, sources)| crate::PrecompiledHeader { header, sources })
        .collect())
}

pub(crate) fn separate(
    root: &Path,
    output: &Path,
    sources: &[PathBuf],
) -> Result<Vec<PathBuf>, String> {
    Ok(expand(root, output, sources)?
        .into_iter()
        .flat_map(|(_, members)| members)
        .collect())
}

pub(crate) fn expand(
    root: &Path,
    output: &Path,
    sources: &[PathBuf],
) -> Result<Vec<(PathBuf, Vec<PathBuf>)>, String> {
    let root = dunce::canonicalize(root).map_err(|e| e.to_string())?;
    let mut result = Vec::new();
    let mut seen = HashSet::new();
    for source in sources {
        let name = source
            .file_name()
            .and_then(|s| s.to_str())
            .ok_or("non-UTF8 source name")?;
        let (suffix, language) = if name.ends_with("+.h.c") {
            (".c.h", "c")
        } else if name.ends_with("+.hpp.cpp") {
            (".cpp.hpp", "cpp")
        } else if name.ends_with("+.h.m") {
            (".m.h", "m")
        } else if name.ends_with("+.hpp.mm") {
            (".mm.hpp", "mm")
        } else {
            result.push((source.clone(), vec![source.clone()]));
            continue;
        };
        println!("cargo:rerun-if-changed={}", source.display());
        let content =
            fs::read_to_string(source).map_err(|e| format!("read {}: {e}", source.display()))?;
        let mut headers = Vec::new();
        let mut members = Vec::new();
        for line in content.lines().map(str::trim) {
            if line.is_empty()
                || line.starts_with("/*")
                || line.starts_with('*')
                || line.starts_with("//")
            {
                continue;
            }
            // Fail closed if a group acquires conditionals or other directives:
            // selecting members must not silently change their build semantics.
            let include = line
                .strip_prefix("#include \"")
                .and_then(|s| s.strip_suffix('"'))
                .ok_or_else(|| {
                    format!(
                        "cannot separate non-include group line in {}: {line}",
                        source.display()
                    )
                })?;
            let path = dunce::canonicalize(root.join(include))
                .map_err(|e| format!("group include {include}: {e}"))?;
            if !path.starts_with(&root) {
                return Err(format!("group include leaves source root: {include}"));
            }
            println!("cargo:rerun-if-changed={}", path.display());
            if include.ends_with(suffix) {
                members.push(path);
            } else {
                headers.push(path);
            }
        }
        if members.is_empty() {
            return Err(format!(
                "group contains no {suffix} implementation members: {}",
                source.display()
            ));
        }
        let mut expanded = Vec::new();
        for member in members {
            if !seen.insert(member.clone()) {
                return Err(format!(
                    "implementation appears in multiple groups: {}",
                    member.display()
                ));
            }
            let relative = member.strip_prefix(&root).map_err(|e| e.to_string())?;
            let wrapper = output.join(relative).with_extension(format!(
                "{}.{}",
                relative
                    .extension()
                    .and_then(|s| s.to_str())
                    .unwrap_or_default(),
                language
            ));
            let mut unit =
                String::from("/* Individual translation unit generated by obs-build. */\n");
            for include in headers.iter().chain(std::iter::once(&member)) {
                let path = dunce::simplified(include)
                    .to_str()
                    .ok_or("non-UTF8 include path")?
                    .replace('\\', "/");
                if path.contains(['\n', '\r', '"']) {
                    return Err(format!("include path cannot be represented: {path:?}"));
                }
                unit.push_str(&format!("#include \"{path}\"\n"));
            }
            if fs::read_to_string(&wrapper).ok().as_deref() != Some(&unit) {
                fs::create_dir_all(wrapper.parent().ok_or("wrapper has no parent")?)
                    .map_err(|e| e.to_string())?;
                fs::write(&wrapper, unit).map_err(|e| e.to_string())?;
            }
            expanded.push(wrapper);
        }
        result.push((source.clone(), expanded));
    }
    Ok(result)
}
